import streamlit as st
import tensorflow as tf
import numpy as np
import joblib

# Load scaler
scaler = joblib.load('scaler.pkl')
label_encoder = joblib.load('label_encoder.pkl')

# Load model TFLite
interpreter = tf.lite.Interpreter(model_path="flood_prediction.tflite")
interpreter.allocate_tensors()

input_details = interpreter.get_input_details()
output_details = interpreter.get_output_details()

# Judul aplikasi
st.title("Sistem Prediksi Risiko Banjir")
st.write("Masukkan faktor-faktor lingkungan berikut untuk memprediksi risiko banjir.")

# Daftar input (sesuai urutan kolom pada dataset flood.csv)
input_labels = [
    "MonsoonIntensity", "TopographyDrainage", "RiverManagement", "Deforestation",
    "Urbanization", "ClimateChange", "DamsQuality", "Siltation",
    "AgriculturalPractices", "Encroachments", "WasteDisposal", "LandUseChange",
    "IndustrialActivity", "DrainageSystems", "CoastalVulnerability", "Landslides",
    "Watersheds", "DeterioratingInfrastructure", "PopulationScore", "WetlandLoss"
]

# Ambil input pengguna
user_input = []
for label in input_labels:
    value = st.slider(label, min_value=0, max_value=10, value=5)
    user_input.append(value)

if st.button("Prediksi Risiko Banjir"):
    input_data = np.array([user_input])
    input_scaled = scaler.transform(input_data).astype(np.float32)

    interpreter.set_tensor(input_details[0]['index'], input_scaled)
    interpreter.invoke()
    prediction = interpreter.get_tensor(output_details[0]['index'])[0][0]

    # Kategorisasi hasil
    if prediction < 0.4:
        category = "RENDAH"
    elif prediction < 0.7:
        category = "SEDANG"
    else:
        category = "TINGGI"

    st.success(f"Probabilitas banjir: **{prediction:.3f}**")
    st.info(f"Kategori risiko: **{category}**")